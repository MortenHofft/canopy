def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def store(src, dst):
    """Copy src to dst, gzip -9 -n when large. Returns final path."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    size = os.path.getsize(src)
    if size > GZIP_OVER and not dst.endswith('.gz'):
        dst += '.gz'
        with open(src, 'rb') as fi, open(dst, 'wb') as raw:
            with gzip.GzipFile(filename='', mode='wb', fileobj=raw, compresslevel=9, mtime=0) as fo:
                shutil.copyfileobj(fi, fo)
    else:
        shutil.copyfile(src, dst)
    return dst


def fmt(x):
    if x is None:
        return '-'
    if isinstance(x, float):
        return ('%.4g' % x)
    return str(x)


def gbif_summary(scratch, key):
    if not key:
        return None
    tsv = os.path.join(scratch, 'gbif', key + '.tsv')
    sj = os.path.join(scratch, 'gbif', key + '.summary.json')
    if not (os.path.exists(tsv) and os.path.exists(sj) and os.path.getsize(sj) > 0):
        return {'status': 'not computed'}
    s = json.load(open(sj))
    occ = []
    zero = 0
    rows = [l.rstrip('\n').split('\t') for l in open(tsv)][1:]
    for r in rows:
        if len(r) >= 8 and r[7] != '':
            occ.append(int(r[7]))
            zero += int(r[7]) == 0
    s['median_occurrences'] = statistics.median(occ) if occ else None
    s['sample_with_zero_occurrences'] = zero
    s['tsv'] = tsv
    return s


def main(a):
    scratch, out = os.path.abspath(a[1]), os.path.abspath(a[2])
    ens_dirs = {'ens-ncrna-102': 'ensembl-ncrna-15435', 'ens-ncrna-399': 'ensembl-ncrna-14845'}
    manifest = []
    for d in DATASETS:
        folder = os.path.join(out, d['folder'])
        if os.path.isdir(folder):
            shutil.rmtree(folder)
        os.makedirs(folder)
        finals = []
        for src, dst in d['files']:
            if d.get('abs_src'):
                sp = os.path.join(scratch, src)
            else:
                sp = os.path.join(out, '_stage', src.split('.')[0], src)  # replaced below
            # ensembl extraction outputs live in the staging dirs produced by ensembl_emf_extract.py
            if not d.get('abs_src'):
                key = list(d['srcdir'].keys())[0]
                sp = os.path.join(scratch, 'ens-extract', d['srcdir'][key], src)
            fin = store(sp, os.path.join(folder, dst))
            finals.append(fin)
        main_final = [f for f in finals if os.path.basename(f) in (d['main'], d['main'] + '.gz')][0]
        reports = treecheck.report(main_final)
        r0 = reports[0]
        g = gbif_summary(scratch, d.get('gbif'))
        if g and g.get('tsv'):
            shutil.copyfile(g['tsv'], os.path.join(folder, 'gbif_match_sample.tsv'))
            finals.append(os.path.join(folder, 'gbif_match_sample.tsv'))
            g = {k: v for k, v in g.items() if k != 'tsv'}
        files = [{'path': os.path.relpath(f, out), 'bytes': os.path.getsize(f), 'sha256': sha256(f)} for f in finals]
        rec = {k: d[k] for k in ('id', 'folder', 'title', 'fmt', 'extra', 'url', 'licence', 'citation', 'how', 'join', 'quirks', 'bl')}
        rec.update({'main_tree': os.path.relpath(main_final, out), 'trees_in_main_file': len(reports),
                    'tips': r0['tips'], 'internal_nodes': r0['internal_nodes'], 'root_children': r0['root_children'],
                    'polytomies': r0['polytomies'], 'internal_labelled': r0['internal_labelled'],
                    'branch_lengths': r0['branch_lengths'], 'format_detected': r0['format'],
                    'comment_keys': r0.get('comment_keys'), 'gbif_match': g, 'files': files,
                    'total_bytes': sum(f['bytes'] for f in files), 'retrieved': RETRIEVED})
        manifest.append(rec)
        write_notes(folder, rec)
        print('built', d['id'], r0['tips'], 'tips', rec['total_bytes'], 'bytes')
    edge = []
    ed = os.path.join(out, 'edge-cases')
    for fn in sorted(os.listdir(ed)):
        fp = os.path.join(ed, fn)
        entry = {'path': 'edge-cases/' + fn, 'bytes': os.path.getsize(fp), 'sha256': sha256(fp), 'hand_made': True,
                 'licence': 'CC0 1.0 (hand-made, not real data)'}
        if not fn.endswith('.md'):
            try:
                rr = treecheck.report(fp)
                entry['trees'] = len(rr)
                entry['tips'] = [x['tips'] for x in rr][:5]
            except Exception as e:  # report parse problems instead of hiding them
                entry['parse_error'] = str(e)
        edge.append(entry)
    json.dump({'generated_by': 'scripts/build_catalogue.py', 'retrieved': RETRIEVED, 'datasets': manifest, 'edge_cases': edge},
              open(os.path.join(out, 'manifest.json'), 'w'), indent=1, sort_keys=True)
    write_readme(out, manifest)


def blsummary(b):
    if not b.get('present'):
        return 'none'
    s = 'n=%d' % b['n_with']
    s += ' min %s max %s med %s' % (fmt(b['min']), fmt(b['max']), fmt(b['median']))
    s += ' max/med %s' % (fmt(b['max_over_median']) if b.get('max_over_median') else 'n/a (median 0)')
    s += '; zero %d neg %d missing %d' % (b['n_zero'], b['n_negative'], b['n_missing'])
    s += '; %s' % ('ultrametric' if b.get('ultrametric') else 'not ultrametric')
    return s


